/* =========================================
   BUILD EXPERIENCE
   ========================================= */

function buildExperience(
    experience
) {

    const container =
        document.getElementById(
            experience.containerId
        );


    if (!container) {

        console.warn(
            "Experience container not found:",
            experience.containerId
        );

        return;

    }


    container.innerHTML = "";


    /* =====================================
       EXPERIENCE GRID
       ===================================== */

    const grid =
        document.createElement(
            "div"
        );


    grid.classList.add(
        "experience-grid"
    );


    /* =====================================
       MAIN EXPERIENCE CARD
       ===================================== */

    const businessCell =
        document.createElement(
            "article"
        );


    businessCell.classList.add(
        "experience-cell",
        "experience-business"
    );


    /* =====================================
       BANNER
       ===================================== */

    const banner =
        document.createElement(
            "div"
        );


    banner.classList.add(
        "experience-banner"
    );


    if (experience.banner) {

        const bannerImage =
            document.createElement(
                "img"
            );


        bannerImage.src =
            experience.banner;


        bannerImage.alt =
            `${experience.company} banner`;


        bannerImage.loading =
            "lazy";


        bannerImage.addEventListener(
            "error",
            () => {

                console.warn(
                    "Banner failed to load:",
                    experience.banner
                );

                bannerImage.remove();

            }
        );


        banner.appendChild(
            bannerImage
        );

    }


    /* =====================================
       HEADER
       ===================================== */

    const header =
        document.createElement(
            "div"
        );


    header.classList.add(
        "experience-header"
    );


    /* =====================================
       IDENTITY
       ===================================== */

    const identity =
        document.createElement(
            "div"
        );


    identity.classList.add(
        "experience-identity"
    );


    /* =====================================
       COMPANY ICON
       ===================================== */

    const iconWrapper =
        document.createElement(
            "div"
        );


    iconWrapper.classList.add(
        "experience-icon"
    );


    const iconFallback =
        document.createElement(
            "span"
        );


    iconFallback.classList.add(
        "experience-icon-fallback"
    );


    iconFallback.textContent =
        experience.iconFallback;


    const icon =
        document.createElement(
            "img"
        );


    icon.src =
        experience.icon;


    icon.alt =
        `${experience.company} logo`;


    icon.addEventListener(
        "load",
        () => {

            iconFallback.style.display =
                "none";

        }
    );


    icon.addEventListener(
        "error",
        () => {

            console.warn(
                "Experience icon failed to load:",
                experience.icon
            );

            icon.style.display =
                "none";

        }
    );


    iconWrapper.appendChild(
        iconFallback
    );


    iconWrapper.appendChild(
        icon
    );


    /* =====================================
       TITLE AREA
       ===================================== */

    const titleArea =
        document.createElement(
            "div"
        );


    titleArea.classList.add(
        "experience-business-title"
    );


    const companyName =
        document.createElement(
            "span"
        );


    companyName.classList.add(
        "experience-eyebrow"
    );


    companyName.textContent =
        experience.company;


    const positionTitle =
        document.createElement(
            "h2"
        );


    positionTitle.textContent =
        experience.position;


    titleArea.appendChild(
        companyName
    );


    titleArea.appendChild(
        positionTitle
    );


    /* =====================================
       BUILD IDENTITY
       ===================================== */

    identity.appendChild(
        iconWrapper
    );


    identity.appendChild(
        titleArea
    );


    /* =====================================
       TYPE BADGE
       ===================================== */

    const typeBadge =
        document.createElement(
            "span"
        );


    typeBadge.classList.add(
        "experience-type"
    );


    typeBadge.textContent =
        experience.type;


    /* =====================================
       BUILD HEADER
       ===================================== */

    header.appendChild(
        identity
    );


    header.appendChild(
        typeBadge
    );


    /* =====================================
       DETAIL CELLS
       ===================================== */

    const detailGrid =
        document.createElement(
            "div"
        );


    detailGrid.classList.add(
        "experience-details"
    );


    const locationCell =
        createExperienceDetailCell(
            "Location",
            experience.location,
            "⌖"
        );


    const timelineCell =
        createExperienceTimelineCell(
            experience.startDate,
            experience.endDate
        );


    detailGrid.appendChild(
        locationCell
    );


    detailGrid.appendChild(
        timelineCell
    );


    /* =====================================
       RESPONSIBILITIES
       ===================================== */

    const responsibilitiesCell =
        document.createElement(
            "div"
        );


    responsibilitiesCell.classList.add(
        "experience-detail-cell",
        "experience-responsibilities"
    );


    const responsibilitiesContent =
        document.createElement(
            "div"
        );


    responsibilitiesContent.classList.add(
        "experience-responsibilities-content"
    );


    const responsibilityLabel =
        document.createElement(
            "span"
        );


    responsibilityLabel.classList.add(
        "experience-cell-label"
    );


    responsibilityLabel.textContent =
        "Responsibilities";


    const responsibilityTitle =
        document.createElement(
            "h3"
        );


    responsibilityTitle.textContent =
        "What I did";


    const responsibilityList =
        document.createElement(
            "ul"
        );


    responsibilityList.classList.add(
        "experience-responsibility-list"
    );


    experience.responsibilities.forEach(
        responsibility => {

            const listItem =
                document.createElement(
                    "li"
                );


            listItem.textContent =
                responsibility;


            responsibilityList.appendChild(
                listItem
            );

        }
    );


    responsibilitiesContent.appendChild(
        responsibilityLabel
    );


    responsibilitiesContent.appendChild(
        responsibilityTitle
    );


    responsibilitiesContent.appendChild(
        responsibilityList
    );


    responsibilitiesCell.appendChild(
        responsibilitiesContent
    );


    /* =====================================
       BUILD MAIN CARD
       ===================================== */

    businessCell.appendChild(
        banner
    );


    businessCell.appendChild(
        header
    );


    businessCell.appendChild(
        detailGrid
    );


    businessCell.appendChild(
        responsibilitiesCell
    );


    /* =====================================
       EXPERIENCE LINKS
       ===================================== */

    if (
        Array.isArray(
            experience.links
        ) &&
        experience.links.length > 0
    ) {

        const linkSection =
            createExperienceLinks(
                experience.links
            );


        businessCell.appendChild(
            linkSection
        );

    }


    /* =====================================
       FINISH CARD
       ===================================== */

    grid.appendChild(
        businessCell
    );


    container.appendChild(
        grid
    );

}


/* =========================================
   CREATE EXPERIENCE LINKS
   ========================================= */

function createExperienceLinks(
    links
) {

    const section =
        document.createElement(
            "div"
        );


    section.classList.add(
        "experience-links"
    );


    /* =====================================
       LABEL
       ===================================== */

    const label =
        document.createElement(
            "span"
        );


    label.classList.add(
        "experience-links-label"
    );


    label.textContent =
        "View More";


    /* =====================================
       BUTTON CONTAINER
       ===================================== */

    const buttonContainer =
        document.createElement(
            "div"
        );


    buttonContainer.classList.add(
        "experience-link-buttons"
    );


    /* =====================================
       CREATE BUTTONS
       ===================================== */

    links.forEach(
        linkItem => {

            if (
                !linkItem ||
                !linkItem.name ||
                !linkItem.link
            ) {

                return;

            }


            const button =
                document.createElement(
                    "a"
                );


            button.classList.add(
                "experience-link-button"
            );


            button.href =
                linkItem.link;


            button.textContent =
                linkItem.name;


            /*
                External links open in
                a new browser tab.
            */

            if (
                linkItem.link.startsWith(
                    "http://"
                ) ||
                linkItem.link.startsWith(
                    "https://"
                )
            ) {

                button.target =
                    "_blank";


                button.rel =
                    "noopener noreferrer";

            }


            /* =================================
               ARROW
               ================================= */

            const arrow =
                document.createElement(
                    "span"
                );


            arrow.classList.add(
                "experience-link-arrow"
            );


            arrow.textContent =
                "→";


            button.appendChild(
                arrow
            );


            buttonContainer.appendChild(
                button
            );

        }
    );


    section.appendChild(
        label
    );


    section.appendChild(
        buttonContainer
    );


    return section;

}


/* =========================================
   CREATE DETAIL CELL
   ========================================= */

function createExperienceDetailCell(
    label,
    value,
    symbol
) {

    const cell =
        document.createElement(
            "div"
        );


    cell.classList.add(
        "experience-detail-cell"
    );


    /* =====================================
       ICON
       ===================================== */

    const icon =
        document.createElement(
            "span"
        );


    icon.classList.add(
        "experience-info-icon"
    );


    icon.textContent =
        symbol;


    /* =====================================
       CONTENT
       ===================================== */

    const content =
        document.createElement(
            "div"
        );


    content.classList.add(
        "experience-detail-content"
    );


    const labelElement =
        document.createElement(
            "span"
        );


    labelElement.classList.add(
        "experience-cell-label"
    );


    labelElement.textContent =
        label;


    const valueElement =
        document.createElement(
            "strong"
        );


    valueElement.textContent =
        value;


    content.appendChild(
        labelElement
    );


    content.appendChild(
        valueElement
    );


    cell.appendChild(
        icon
    );


    cell.appendChild(
        content
    );


    return cell;

}


